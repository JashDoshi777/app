    title = Column(Text)
    content = Column(Text)
    raw_score = Column(Float)
    compound_score = Column(Float)
    positive = Column(Float)
    negative = Column(Float)
    neutral = Column(Float)
    label = Column(String(20))  # "BULLISH", "BEARISH", "NEUTRAL"
    symbol_mentioned = Column(String(50))


