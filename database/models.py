"""
Database ORM models — tracks EVERYTHING.
"Data is King" — every signal, trade, tick, sentiment score is persisted.
"""

from datetime import datetime
from sqlalchemy import (
    Column, Integer, Float, String, DateTime, Boolean, Text, JSON,
    BigInteger, Enum as SQLEnum, Index,
)
from database.connection import Base
import enum


# ═══════════════════════════════════════════════════════════
#  ENUMS
# ═══════════════════════════════════════════════════════════

class OrderSide(str, enum.Enum):
    BUY = "BUY"
    SELL = "SELL"


class OrderType(str, enum.Enum):
    MARKET = "MARKET"
    LIMIT = "LIMIT"


class OptionType(str, enum.Enum):
    CE = "CE"
    PE = "PE"


class TradeStatus(str, enum.Enum):
    OPEN = "OPEN"
    CLOSED = "CLOSED"
    CANCELLED = "CANCELLED"
    EXPIRED = "EXPIRED"


class SignalDirection(str, enum.Enum):
    STRONG_BUY = "STRONG_BUY"
    BUY = "BUY"
    NEUTRAL = "NEUTRAL"
    SELL = "SELL"
    STRONG_SELL = "STRONG_SELL"


class MarketRegime(str, enum.Enum):
    TRENDING_UP = "TRENDING_UP"
    TRENDING_DOWN = "TRENDING_DOWN"
    SIDEWAYS = "SIDEWAYS"
    HIGH_VOLATILITY = "HIGH_VOLATILITY"
    LOW_VOLATILITY = "LOW_VOLATILITY"


class StrategyName(str, enum.Enum):
    IRON_CONDOR = "IRON_CONDOR"
    SHORT_STRADDLE = "SHORT_STRADDLE"
    SHORT_STRANGLE = "SHORT_STRANGLE"
    LONG_STRADDLE = "LONG_STRADDLE"
    LONG_STRANGLE = "LONG_STRANGLE"
    BULL_CALL_SPREAD = "BULL_CALL_SPREAD"
    BULL_PUT_SPREAD = "BULL_PUT_SPREAD"
    BEAR_CALL_SPREAD = "BEAR_CALL_SPREAD"
    BEAR_PUT_SPREAD = "BEAR_PUT_SPREAD"
    CALENDAR_SPREAD = "CALENDAR_SPREAD"
    NAKED_CE = "NAKED_CE"
    NAKED_PE = "NAKED_PE"


# ═══════════════════════════════════════════════════════════
#  TRADE LOG — Every single trade ever taken
# ═══════════════════════════════════════════════════════════

class Trade(Base):
    __tablename__ = "trades"

    id = Column(Integer, primary_key=True, autoincrement=True)
    created_at = Column(DateTime, default=datetime.utcnow, index=True)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Instrument details
    symbol = Column(String(50), nullable=False, index=True)
    exchange_segment = Column(String(20), nullable=False)
    security_id = Column(String(30))
    option_type = Column(SQLEnum(OptionType))
    strike_price = Column(Float)
    expiry_date = Column(String(20))

    # Order details
    side = Column(SQLEnum(OrderSide), nullable=False)
    order_type = Column(SQLEnum(OrderType), default=OrderType.MARKET)
    quantity = Column(Integer, nullable=False)
    lot_size = Column(Integer)

    # Prices
    entry_price = Column(Float, nullable=False)
    exit_price = Column(Float)
    stoploss_price = Column(Float)
    target_price = Column(Float)

    # P&L
    brokerage = Column(Float, default=0)
    slippage = Column(Float, default=0)
    gross_pnl = Column(Float, default=0)
    net_pnl = Column(Float, default=0)

    # Status
    status = Column(SQLEnum(TradeStatus), default=TradeStatus.OPEN, index=True)
    exit_reason = Column(String(100))

    # Strategy info
    strategy = Column(SQLEnum(StrategyName))
    strategy_params = Column(JSON)

    # Signal info at entry
    entry_signal_score = Column(Float)
    entry_signal_direction = Column(SQLEnum(SignalDirection))
    entry_signals_detail = Column(JSON)

    # Greeks at entry
    entry_delta = Column(Float)
    entry_gamma = Column(Float)
    entry_theta = Column(Float)
    entry_vega = Column(Float)
    entry_iv = Column(Float)

    # Greeks at exit
    exit_delta = Column(Float)
    exit_gamma = Column(Float)
    exit_theta = Column(Float)
    exit_vega = Column(Float)
    exit_iv = Column(Float)

    # Market context
    underlying_price_at_entry = Column(Float)
    underlying_price_at_exit = Column(Float)
    vix_at_entry = Column(Float)
    vix_at_exit = Column(Float)
    pcr_at_entry = Column(Float)
    sentiment_score_at_entry = Column(Float)
    market_regime_at_entry = Column(SQLEnum(MarketRegime))

    # Timestamps
    entry_time = Column(DateTime, index=True)
    exit_time = Column(DateTime)

    __table_args__ = (
        Index("ix_trades_symbol_status", "symbol", "status"),
        Index("ix_trades_strategy_created", "strategy", "created_at"),
    )


# ═══════════════════════════════════════════════════════════
#  SIGNAL LOG — Every signal generated by the system
# ═══════════════════════════════════════════════════════════

class Signal(Base):
    __tablename__ = "signals"

    id = Column(Integer, primary_key=True, autoincrement=True)
    created_at = Column(DateTime, default=datetime.utcnow, index=True)

    symbol = Column(String(50), nullable=False, index=True)
    direction = Column(SQLEnum(SignalDirection), nullable=False)
    score = Column(Float, nullable=False)

    # Breakdown
    technical_score = Column(Float)
    greeks_score = Column(Float)
    oi_score = Column(Float)
    sentiment_score = Column(Float)
    regime_score = Column(Float)

    # Details
    technical_detail = Column(JSON)
    greeks_detail = Column(JSON)
    oi_detail = Column(JSON)
    sentiment_detail = Column(JSON)
    regime = Column(SQLEnum(MarketRegime))

    # Was this signal acted upon?
    acted_upon = Column(Boolean, default=False)
    trade_id = Column(Integer)

    underlying_price = Column(Float)
    vix = Column(Float)


